#!/usr/bin/env bash
# Install generic DisplayLink system config and bind it to this machine.
# --apply-monitors also writes ~/.config/hypr/monitors.lua from current outputs.
set -euo pipefail
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=lib.sh
source "$SCRIPT_DIR/lib.sh"

ROOT="$(repo_root)"
CONF="$ROOT/config/displaylink"
APPLY_MONITORS=0
[[ "${1:-}" == "--apply-monitors" ]] && APPLY_MONITORS=1

need_cmd sudo install
need_sudo

pci="$(primary_gpu_pci || true)"
if [[ -z "${pci:-}" ]]; then
  echo "Could not detect a PCI GPU. Plug in a native monitor or pass the PCI id by editing the udev rule after install." >&2
  pci="0000:00:00.0"
fi
vendor="$(gpu_vendor_from_pci "$pci")"
symlink="dri/${vendor}-gpu"

echo "Primary GPU PCI $pci ($vendor) -> /dev/$symlink"

tmp_rules="$(mktemp)"
{
  echo "# Generated by omarchy-setup displaylink-configure.sh — do not copy this file into git."
  echo "KERNEL==\"card*\", KERNELS==\"$pci\", SUBSYSTEM==\"drm\", SUBSYSTEMS==\"pci\", SYMLINK+=\"$symlink\""
  echo "KERNEL==\"card*\", KERNELS==\"evdi.0\", SUBSYSTEM==\"drm\", SUBSYSTEMS==\"platform\", SYMLINK+=\"dri/evdi0\""
  echo "KERNEL==\"card*\", KERNELS==\"evdi.1\", SUBSYSTEM==\"drm\", SUBSYSTEMS==\"platform\", SYMLINK+=\"dri/evdi1\""
} >"$tmp_rules"

install_file "$CONF/evdi.conf" /etc/modprobe.d/evdi.conf
install_file "$CONF/evdi-modules-load.conf" /etc/modules-load.d/evdi.conf
install_file "$tmp_rules" /etc/udev/rules.d/99-drm-stable-names.rules
rm -f "$tmp_rules"
sudo mkdir -p /etc/systemd/system/displaylink.service.d
install_file "$CONF/displaylink-early.conf" /etc/systemd/system/displaylink.service.d/early.conf

sudo udevadm control --reload
sudo udevadm trigger --subsystem-match=drm
sudo systemctl daemon-reload
sudo systemctl enable displaylink.service

mkdir -p "${XDG_CONFIG_HOME:-$HOME/.config}/uwsm"
env_file="${XDG_CONFIG_HOME:-$HOME/.config}/uwsm/env-hyprland"
touch "$env_file"
aq="/dev/${symlink}:/dev/dri/evdi0:/dev/dri/evdi1"
block_file="$(mktemp)"
{
  echo "# BEGIN omarchy-setup displaylink"
  echo "export AQ_DRM_DEVICES=\"$aq\""
  if [[ "$vendor" == nvidia ]]; then
    echo "export AQ_NO_MODIFIERS=1"
    echo "export AQ_MGPU_NO_EXPLICIT=1"
  fi
  echo "# END omarchy-setup displaylink"
} >"$block_file"

if grep -q 'BEGIN omarchy-setup displaylink' "$env_file"; then
  python3 - "$env_file" "$block_file" <<'PY'
import pathlib, sys
path, block = map(pathlib.Path, sys.argv[1:])
text = path.read_text()
repl = block.read_text().rstrip() + "\n"
start, end = "# BEGIN omarchy-setup displaylink", "# END omarchy-setup displaylink"
i, j = text.find(start), text.find(end)
if i == -1 or j == -1:
    raise SystemExit("marker block incomplete")
j = j + len(end)
path.write_text(text[:i] + repl + text[j:].lstrip("\n"))
PY
else
  printf '\n%s\n' "$(cat "$block_file")" >>"$env_file"
fi
rm -f "$block_file"
echo "Updated $env_file"

suggest_monitors() {
  python3 - <<'PY'
import json, os, subprocess, shutil

def mode_of(m):
    modes = m.get("availableModes") or []
    for cand in ("1920x1080@60.00Hz", "1920x1080@59.94Hz", "2560x1440@60.00Hz"):
        if cand in modes:
            return cand.replace("Hz", "").replace(".00", "")
    w, h, r = m.get("width") or 0, m.get("height") or 0, m.get("refreshRate") or 60
    if w and h:
        return f"{w}x{h}@{int(round(r))}"
    return "preferred"

try:
    raw = subprocess.check_output(["hyprctl", "-j", "monitors"], text=True)
    mons = json.loads(raw)
except Exception as e:
    print(f"-- could not read hyprctl monitors: {e}")
    raise SystemExit(0)

lines = [
    "-- Generated suggestion. Check names with: hyprctl monitors all",
    "local omarchy_gdk_scale = 2",
    'hl.env("GDK_SCALE", tostring(omarchy_gdk_scale))',
    "",
]
x = 0
for m in mons:
    name = m["name"]
    mode = mode_of(m)
    # DisplayLink: pin 60 Hz even if EDID lists higher modes evdi will reject.
    if name.startswith("DVI-I-"):
        mode = "1920x1080@60"
    w = 1920
    if "x" in mode and mode != "preferred":
        w = int(mode.split("x")[0])
    lines.append(
        f'hl.monitor({{ output = "{name}", mode = "{mode}", position = "{x}x0", scale = 1 }})'
    )
    x += w
print("\n".join(lines))
PY
}

echo
echo "=== suggested monitors.lua ==="
suggestion="$(suggest_monitors || true)"
printf '%s\n' "$suggestion"

if (( APPLY_MONITORS )) && grep -q 'hl.monitor' <<<"$suggestion"; then
  dest="${XDG_CONFIG_HOME:-$HOME/.config}/hypr/monitors.lua"
  mkdir -p "$(dirname "$dest")"
  if [[ -f "$dest" ]]; then
    cp "$dest" "$dest.bak.$(date +%s)"
    echo "Backed up $dest"
  fi
  printf '%s\n' "$suggestion" >"$dest"
  echo "Wrote $dest"
  if command -v hyprctl >/dev/null; then
    hyprctl reload >/dev/null || true
    hyprctl configerrors || true
  fi
fi

echo
echo "AQ_* and udev names apply on the next Hyprland session. Reboot with the hub on USB 3."
echo "Verify with: $SCRIPT_DIR/displaylink-detect.sh"
