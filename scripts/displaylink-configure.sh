#!/usr/bin/env bash
# Install generic DisplayLink system config and bind it to this machine.
# Usage: displaylink-configure.sh [--apply-monitors] [--no-modifiers]
#   --apply-monitors  append hl.monitor lines for evdi outputs missing from ~/.config/hypr/monitors.lua
#                     (never rewrites existing lines; rolls back if hyprctl configerrors is non-empty)
#   --no-modifiers    also export AQ_NO_MODIFIERS=1 (NVIDIA workaround; can grey out native outputs)
set -euo pipefail
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=lib.sh
source "$SCRIPT_DIR/lib.sh"

ROOT="$(repo_root)"
CONF="$ROOT/config/displaylink"
APPLY_MONITORS=0
NO_MODIFIERS=0
for arg in "$@"; do
  case "$arg" in
    --apply-monitors) APPLY_MONITORS=1 ;;
    --no-modifiers) NO_MODIFIERS=1 ;;
    *) echo "Unknown option: $arg" >&2; exit 2 ;;
  esac
done

need_cmd sudo install python3
need_sudo

pci="$(primary_gpu_pci || true)"
tmp_rules="$(mktemp)"
{
  echo "# Generated by omarchy-setup displaylink-configure.sh — do not copy this file into git."
  if [[ -n "${pci:-}" ]]; then
    vendor="$(gpu_vendor_from_pci "$pci")"
    echo "Primary GPU PCI $pci ($vendor) -> /dev/dri/${vendor}-gpu" >&2
    echo "KERNEL==\"card*\", KERNELS==\"$pci\", SUBSYSTEM==\"drm\", SUBSYSTEMS==\"pci\", SYMLINK+=\"dri/${vendor}-gpu\""
  else
    # The env block falls back to the first non-evdi card, so skipping the rule is safe.
    echo "Could not detect a PCI GPU; skipping the GPU symlink rule (the env block falls back to the first non-evdi card)." >&2
  fi
  echo "KERNEL==\"card*\", KERNELS==\"evdi.0\", SUBSYSTEM==\"drm\", SUBSYSTEMS==\"platform\", SYMLINK+=\"dri/evdi0\""
  echo "KERNEL==\"card*\", KERNELS==\"evdi.1\", SUBSYSTEM==\"drm\", SUBSYSTEMS==\"platform\", SYMLINK+=\"dri/evdi1\""
} >"$tmp_rules"

install_file "$CONF/evdi.conf" /etc/modprobe.d/evdi.conf
install_file "$CONF/evdi-modules-load.conf" /etc/modules-load.d/evdi.conf
install_file "$tmp_rules" /etc/udev/rules.d/99-drm-stable-names.rules
rm -f "$tmp_rules"
sudo mkdir -p /etc/systemd/system/displaylink.service.d
install_file "$CONF/displaylink-early.conf" /etc/systemd/system/displaylink.service.d/early.conf

sudo udevadm control --reload
sudo udevadm trigger --subsystem-match=drm
sudo systemctl daemon-reload
sudo systemctl enable displaylink.service

mkdir -p "${XDG_CONFIG_HOME:-$HOME/.config}/uwsm"
env_file="${XDG_CONFIG_HOME:-$HOME/.config}/uwsm/env-hyprland"
touch "$env_file"
[[ -s "$env_file" ]] && cp "$env_file" "$env_file.bak.$(date +%s)"
block_file="$(mktemp)"
{
  echo "# BEGIN omarchy-setup displaylink"
  cat "$CONF/env-hyprland.example"
  if (( NO_MODIFIERS )); then
    echo 'export AQ_NO_MODIFIERS=1'
  fi
  echo "# END omarchy-setup displaylink"
} >"$block_file"

if grep -q 'BEGIN omarchy-setup displaylink' "$env_file"; then
  python3 - "$env_file" "$block_file" <<'PY'
import pathlib, sys
path, block = map(pathlib.Path, sys.argv[1:])
text = path.read_text()
repl = block.read_text().rstrip() + "\n"
start, end = "# BEGIN omarchy-setup displaylink", "# END omarchy-setup displaylink"
i, j = text.find(start), text.find(end)
if i == -1 or j == -1:
    raise SystemExit("marker block incomplete")
j = j + len(end)
path.write_text(text[:i] + repl + text[j:].lstrip("\n"))
PY
else
  printf '\n%s\n' "$(cat "$block_file")" >>"$env_file"
fi
rm -f "$block_file"
echo "Updated $env_file"

# Prints only the hl.monitor lines for evdi outputs that monitors.lua does not mention yet.
# Existing lines (including disabled = true) are left alone. Notes go to stderr.
suggest_monitors() {
  python3 - "$1" <<'PY'
import glob, json, os, re, subprocess, sys

path = sys.argv[1]
try:
    mons = json.loads(subprocess.check_output(["hyprctl", "-j", "monitors", "all"], text=True))
except Exception as e:
    print(f"could not read hyprctl monitors: {e}", file=sys.stderr)
    raise SystemExit(0)

text = open(path).read() if os.path.exists(path) else ""
code = [l for l in text.splitlines() if not l.lstrip().startswith("--")]
configured = set()
right = 0.0
for line in code:
    m = re.search(r'output\s*=\s*"([^"]*)"', line)
    if not m or "hl.monitor" not in line:
        continue
    configured.add(m.group(1))
    if "disabled" in line and re.search(r'disabled\s*=\s*true', line):
        continue
    mode = re.search(r'mode\s*=\s*"(\d+)x(\d+)', line)
    pos = re.search(r'position\s*=\s*"(-?\d+)x(-?\d+)"', line)
    sc = re.search(r'scale\s*=\s*([0-9.]+)', line)
    if mode and pos:
        scale = float(sc.group(1)) if sc else 1.0
        right = max(right, int(pos.group(1)) + int(mode.group(1)) / scale)
# What is actually laid out right now also counts.
for m in mons:
    if m.get("disabled"):
        continue
    right = max(right, m["x"] + m["width"] / (m.get("scale") or 1))

def is_evdi(name):
    for card in glob.glob(f"/sys/class/drm/card*-{name}"):
        if "/evdi." in os.path.realpath(card):
            return True
    return name.startswith("DVI-I-")

x = int(right + 0.999)
out = []
for m in mons:
    name = m["name"]
    if name in configured:
        print(f"{name}: already in monitors.lua, left as is", file=sys.stderr)
        continue
    if not is_evdi(name):
        continue
    modes = m.get("availableModes") or []
    mode = "1920x1080@60" if (not modes or any(s.startswith("1920x1080@60") for s in modes)) else "preferred"
    out.append(f'hl.monitor({{ output = "{name}", mode = "{mode}", position = "{x}x0", scale = 1 }})')
    x += 1920
print("\n".join(out))
PY
}

monitors_file="${XDG_CONFIG_HOME:-$HOME/.config}/hypr/monitors.lua"
echo
echo "=== evdi outputs missing from monitors.lua ==="
suggestion="$(suggest_monitors "$monitors_file" || true)"
if [[ -z "$suggestion" ]]; then
  echo "(none)"
else
  printf '%s\n' "$suggestion"
fi

if (( APPLY_MONITORS )); then
  if [[ -z "$suggestion" ]]; then
    echo "Nothing to add; monitors.lua untouched."
  else
    mkdir -p "$(dirname "$monitors_file")"
    backup=""
    if [[ -f "$monitors_file" ]]; then
      backup="$monitors_file.bak.$(date +%s)"
      cp "$monitors_file" "$backup"
      echo "Backed up to $backup"
    fi
    {
      echo
      echo "-- Added by omarchy-setup displaylink-configure.sh"
      printf '%s\n' "$suggestion"
    } >>"$monitors_file"
    echo "Appended to $monitors_file"
    if command -v hyprctl >/dev/null; then
      hyprctl reload >/dev/null || true
      errors="$(hyprctl configerrors 2>&1 || true)"
      if [[ -n "${errors//[[:space:]]/}" ]]; then
        echo "hyprctl reports config errors; restoring the previous monitors.lua:" >&2
        echo "$errors" >&2
        if [[ -n "$backup" ]]; then
          cp "$backup" "$monitors_file"
        else
          rm -f "$monitors_file"
        fi
        hyprctl reload >/dev/null || true
        exit 1
      fi
    fi
  fi
fi

echo
echo "AQ_* and udev names apply on the next Hyprland session. Reboot with the hub on USB 3."
echo "Verify with: $SCRIPT_DIR/displaylink-detect.sh"
